"""
train_escalation_gate.py — the ML component of Tier 0: a learned "escalation gate".

Question it answers: WHEN should a room node wake the (slow, power-hungry) language
model? Hand-written thresholds are brittle; a tiny decision tree trained on situation
windows decides, runs on the ESP32 in microseconds, and is exported as plain C
(no ML runtime, no heap). It NEVER overrides Tier 0 life-safety rules — those run first.

Compared:  H  hand-written heuristic (what home_node.ino used before)
           T  decision tree (exported to firmware)
           T+ tree OR gas-band safety net (what the firmware actually runs)
           IF Isolation Forest trained on routine windows only (unsupervised, gateway-side
              option: learns a household's normal without labelled incidents)

Evaluated on: (a) held-out i.i.d. windows, (b) a SHIFTED "different home, noisier
sensors" set (robustness). ALL DATA IS SIMULATED — label results "simulated".

Usage:  python train_escalation_gate.py    (run simulate_home.py first is optional)
Outputs (results/): gate_report.json, gate_report.md, gate_confusion.png,
                    tree_rules.txt ; and ../home_node/escalation_model.h
"""
import json, os
import numpy as np
from sklearn.tree import DecisionTreeClassifier, export_text
from sklearn.ensemble import IsolationForest
from sklearn.model_selection import cross_val_score, StratifiedKFold
from sklearn.metrics import precision_score, recall_score, f1_score
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from simulate_home import generate, FEATURES

HERE = os.path.dirname(__file__)
RES = os.path.join(HERE, "results")
FW = os.path.join(HERE, "..", "home_node", "escalation_model.h")
os.makedirs(RES, exist_ok=True)
IDX = {f: i for i, f in enumerate(FEATURES)}


def heuristic(X):
    """Mirror of the pre-ML firmware rule."""
    gas = X[:, IDX["gas_pct"]]
    return ((gas > 20) & (gas < 60)) | ((X[:, IDX["quiet_min"]] > 240) &
                                        (X[:, IDX["hour"]] >= 8) & (X[:, IDX["hour"]] <= 20))


def gas_band(X):
    g = X[:, IDX["gas_pct"]]
    return (g > 20) & (g < 60)


def metrics(y, p):
    return dict(precision=round(precision_score(y, p, zero_division=0), 4),
                recall=round(recall_score(y, p), 4), f1=round(f1_score(y, p), 4),
                escalation_rate=round(float(np.mean(p)), 4))


def to_c(tree, n_features):
    t = tree.tree_
    lines = []

    def rec(node, depth):
        pad = "  " * (depth + 1)
        if t.feature[node] == -2:
            v = t.value[node][0]
            lines.append(f"{pad}return {1 if v[1] > v[0] else 0};")
            return
        lines.append(f"{pad}if (f[{t.feature[node]}] <= {t.threshold[node]:.4f}f) {{ "
                     f"/* {FEATURES[t.feature[node]]} */")
        rec(t.children_left[node], depth + 1)
        lines.append(f"{pad}}} else {{")
        rec(t.children_right[node], depth + 1)
        lines.append(f"{pad}}}")
    rec(0, 0)
    body = "\n".join(lines)
    return f"""// AUTO-GENERATED by code/ml/train_escalation_gate.py - do not edit by hand.
// Trained on SIMULATED situation windows; re-train/validate on real node logs (see
// HARDWARE_SETUP.md step 10). Feature order (all float):
//   {", ".join(f"f[{i}]={n}" for i, n in enumerate(FEATURES))}
#pragma once
#define GATE_N_FEATURES {n_features}
// depth={tree.get_depth()} leaves={tree.get_n_leaves()}
inline bool escalation_tree(const float *f) {{
{body}
}}
"""


def main():
    train = generate(16000, seed=1)
    test = generate(8000, seed=2)                                   # i.i.d. held-out
    shifted = generate(8000, seed=3, noise=2.0,                     # "another home"
                       shift={"temp_c": 1.5, "hum_delta": 4.0, "light_ratio": 0.15})
    Xtr, ytr = train[FEATURES].values, train.label.values

    # depth selection by 5-fold CV on the training set (favour small = fits firmware)
    cv = StratifiedKFold(5, shuffle=True, random_state=0)
    cv_scores = {}
    for d in (3, 4, 5, 6, 7, 8):
        clf = DecisionTreeClassifier(max_depth=d, min_samples_leaf=20, random_state=0,
                                     class_weight={0: 1, 1: 3})   # missing an incident is costlier
        cv_scores[d] = float(cross_val_score(clf, Xtr, ytr, cv=cv, scoring="f1").mean())
    best_d = min(d for d, s in cv_scores.items() if s >= max(cv_scores.values()) - 0.003)
    tree = DecisionTreeClassifier(max_depth=best_d, min_samples_leaf=20, random_state=0,
                                  class_weight={0: 1, 1: 3}).fit(Xtr, ytr)

    iso = IsolationForest(n_estimators=200, contamination=0.05, random_state=0)
    iso.fit(Xtr[ytr == 0])

    report = {"note": "SIMULATED DATA", "cv_f1_by_depth": cv_scores, "chosen_depth": best_d,
              "n_train": len(train), "n_test": len(test), "leaves": int(tree.get_n_leaves())}
    fam_recall = {}
    for name, ds in (("iid_test", test), ("shifted_test", shifted)):
        X, y = ds[FEATURES].values, ds.label.values
        preds = {"H_heuristic": heuristic(X),
                 "T_tree": tree.predict(X).astype(bool),
                 "T+_tree_or_gasband": tree.predict(X).astype(bool) | gas_band(X),
                 "IF_isolation_forest": iso.predict(X) == -1}
        report[name] = {k: metrics(y, p) for k, p in preds.items()}
        # per-family recall/false-escalation for the firmware variant
        p = preds["T+_tree_or_gasband"]
        fam = {}
        for f, g in ds.groupby("family"):
            fam[f] = round(float(p[g.index.values].mean()), 3)
        fam_recall[name] = fam
        report[name]["per_family_escalation_rate_T+"] = fam
        # what the gate buys: routine windows that never reach the LLM
        for k, pk in preds.items():
            report[name][k]["routine_suppressed_pct"] = round(
                100 * float(1 - pk[y == 0].mean()), 1)
        report[name]["llm_calls_avoided_vs_escalate_all_pct"] = round(
            100 * (1 - float(p.mean())), 1)

    # write artifacts
    with open(os.path.join(RES, "gate_report.json"), "w") as f:
        json.dump(report, f, indent=2)
    with open(os.path.join(RES, "tree_rules.txt"), "w", encoding="utf-8") as f:
        f.write(export_text(tree, feature_names=FEATURES))
    with open(FW, "w", encoding="utf-8", newline="\n") as f:
        f.write(to_c(tree, len(FEATURES)))

    md = ["# Escalation gate — SIMULATED-data results\n"]
    for name in ("iid_test", "shifted_test"):
        md += [f"## {name}\n", "| Method | Precision | Recall | F1 | Escalation rate |",
               "|---|---|---|---|---|"]
        for k, m in report[name].items():
            if isinstance(m, dict) and "precision" in m:
                md.append(f"| {k} | {m['precision']} | {m['recall']} | {m['f1']} | "
                          f"{m['escalation_rate']} |")
        md.append(f"\nLLM calls avoided vs escalate-everything: "
                  f"{report[name]['llm_calls_avoided_vs_escalate_all_pct']}%\n")
    open(os.path.join(RES, "gate_report.md"), "w", encoding="utf-8").write("\n".join(md))

    # figure: precision/recall bars
    fig, ax = plt.subplots(1, 2, figsize=(9, 3.3), sharey=True)
    for a, name in zip(ax, ("iid_test", "shifted_test")):
        ks = ["H_heuristic", "T_tree", "T+_tree_or_gasband", "IF_isolation_forest"]
        x = np.arange(len(ks))
        a.bar(x - 0.2, [report[name][k]["precision"] for k in ks], 0.4, label="precision")
        a.bar(x + 0.2, [report[name][k]["recall"] for k in ks], 0.4, label="recall")
        a.set_xticks(x); a.set_xticklabels(["heur.", "tree", "tree+gas", "iso-forest"], fontsize=8)
        a.set_title(name.replace("_", " ") + " (simulated)", fontsize=9)
        a.set_ylim(0, 1.05)
    ax[0].legend(fontsize=8)
    plt.tight_layout()
    plt.savefig(os.path.join(RES, "gate_confusion.png"), dpi=200)

    print(json.dumps({k: report[k] for k in ("chosen_depth", "leaves", "cv_f1_by_depth")}, indent=1))
    for name in ("iid_test", "shifted_test"):
        print("\n==", name)
        for k, m in report[name].items():
            if isinstance(m, dict) and "precision" in m:
                print(f"  {k:22s} P={m['precision']:.3f} R={m['recall']:.3f} "
                      f"F1={m['f1']:.3f} esc-rate={m['escalation_rate']:.3f} "
                      f"routine-suppressed={m['routine_suppressed_pct']}%")
        print("  LLM calls avoided vs escalate-all:",
              report[name]["llm_calls_avoided_vs_escalate_all_pct"], "%")
    print("\nwrote", os.path.normpath(FW))


if __name__ == "__main__":
    main()
